#include <stdint.h>
#include <wolfHAL/wolfHAL.h>
#include "wolfHAL_board.h"
#include "test.h"

static const uint8_t key[32] = {
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
    0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
    0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F,
};

static const uint8_t nonce[12] = {
    0xB0, 0xB1, 0xB2, 0xB3, 0xB4, 0xB5, 0xB6, 0xB7,
    0xB8, 0xB9, 0xBA, 0xBB,
};

static const uint8_t aad[16] = {
    0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7,
    0xC8, 0xC9, 0xCA, 0xCB, 0xCC, 0xCD, 0xCE, 0xCF,
};

/* NIST CAVP gcmEncryptExtIV256.rsp: Keylen=256, IVlen=96, PTlen=0, AADlen=128, Taglen=128, Count=0 */
static const uint8_t gmacKey[32] = {
    0x78, 0xDC, 0x4E, 0x0A, 0xAF, 0x52, 0xD9, 0x35,
    0xC3, 0xC0, 0x1E, 0xEA, 0x57, 0x42, 0x8F, 0x00,
    0xCA, 0x1F, 0xD4, 0x75, 0xF5, 0xDA, 0x86, 0xA4,
    0x9C, 0x8D, 0xD7, 0x3D, 0x68, 0xC8, 0xE2, 0x23,
};

static const uint8_t gmacIv[12] = {
    0xD7, 0x9C, 0xF2, 0x2D, 0x50, 0x4C, 0xC7, 0x93,
    0xC3, 0xFB, 0x6C, 0x8A,
};

static const uint8_t gmacAad[16] = {
    0xB9, 0x6B, 0xAA, 0x8C, 0x1C, 0x75, 0xA6, 0x71,
    0xBF, 0xB2, 0xD0, 0x8D, 0x06, 0xBE, 0x5F, 0x36,
};

static const uint8_t gmacTag[16] = {
    0x3E, 0x5D, 0x48, 0x6A, 0xA2, 0xE3, 0x0B, 0x22,
    0xE0, 0x40, 0xB8, 0x57, 0x23, 0xA0, 0x6E, 0x76,
};

/* Vectors generated by tests/crypto/gen_test_vectors.py. gmac128Tag uses
 * gmacKey[0..15] with gmacIv/gmacAad. gmacTagAad<n> use gmacKey/gmacIv over
 * the first n bytes of gmacPartialAad. */
static const uint8_t gmac128Tag[16] = {
    0xE5, 0xE4, 0x9D, 0x25, 0x2B, 0xC1, 0x5C, 0xCA,
    0xBD, 0xE2, 0x80, 0x41, 0xF5, 0xEE, 0x0B, 0xF7,
};

static const uint8_t gmacPartialAad[31] = {
    0x07, 0x14, 0x21, 0x2E, 0x3B, 0x48, 0x55, 0x62,
    0x6F, 0x7C, 0x89, 0x96, 0xA3, 0xB0, 0xBD, 0xCA,
    0xD7, 0xE4, 0xF1, 0xFE, 0x0B, 0x18, 0x25, 0x32,
    0x3F, 0x4C, 0x59, 0x66, 0x73, 0x80, 0x8D,
};

static const uint8_t gmacTagAad0[16] = {
    0xD2, 0xCD, 0x4E, 0x34, 0x89, 0x70, 0xB2, 0x11,
    0xC5, 0xF1, 0x27, 0x6A, 0xAA, 0x76, 0xE2, 0xE1,
};

static const uint8_t gmacTagAad1[16] = {
    0x92, 0x3B, 0x29, 0x22, 0x55, 0xA3, 0xF4, 0xDD,
    0x7F, 0x76, 0xD0, 0x91, 0xF6, 0x58, 0xBC, 0xC8,
};

static const uint8_t gmacTagAad15[16] = {
    0x6C, 0x4B, 0x33, 0xAD, 0x98, 0xB1, 0xB7, 0x41,
    0x7C, 0xC3, 0x1B, 0x2E, 0xC2, 0xED, 0xA6, 0x8A,
};

static const uint8_t gmacTagAad17[16] = {
    0xE9, 0xA2, 0x3E, 0x8E, 0xC5, 0x53, 0x30, 0xB3,
    0xE2, 0xDA, 0x58, 0xCC, 0x1E, 0xC9, 0xAD, 0x0F,
};

static const uint8_t gmacTagAad20[16] = {
    0x43, 0xB5, 0x55, 0xBA, 0xBF, 0x29, 0xE2, 0xC3,
    0x8B, 0x5C, 0xB4, 0x00, 0x06, 0x6C, 0x18, 0xD9,
};

static const uint8_t gmacTagAad31[16] = {
    0xA5, 0x57, 0x1D, 0xA0, 0x2E, 0xBC, 0x83, 0xED,
    0xEB, 0x53, 0x50, 0x9A, 0x99, 0xB1, 0xCE, 0x9A,
};

static const struct {
    size_t aadSz;
    const uint8_t *tag;
} gmacPartialAadCases[] = {
    { 1, gmacTagAad1 },
    { 15, gmacTagAad15 },
    { 17, gmacTagAad17 },
    { 20, gmacTagAad20 },
    { 31, gmacTagAad31 },
};

static void Test_AesGmac_Basic(void)
{
    uint8_t tag1[16] = {0};
    uint8_t tag2[16] = {0};

    WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                         key, 32,
                                         nonce, sizeof(nonce),
                                         aad, sizeof(aad),
                                         tag1, sizeof(tag1)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                         key, 32,
                                         nonce, sizeof(nonce),
                                         aad, sizeof(aad),
                                         tag2, sizeof(tag2)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(tag1, tag2, sizeof(tag1));
}

static void Test_AesGmac_KnownAnswer(void)
{
    uint8_t tag[16] = {0};

    WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                         gmacKey, 32,
                                         gmacIv, sizeof(gmacIv),
                                         gmacAad, sizeof(gmacAad),
                                         tag, sizeof(tag)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(tag, gmacTag, sizeof(gmacTag));
}

static void Test_AesGmac_KnownAnswer128(void)
{
    uint8_t tag[16] = {0};

    WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                         gmacKey, 16,
                                         gmacIv, sizeof(gmacIv),
                                         gmacAad, sizeof(gmacAad),
                                         tag, sizeof(tag)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(tag, gmac128Tag, sizeof(gmac128Tag));
}

static void Test_AesGmac_PartialAad(void)
{
    size_t i;

    for (i = 0; i < sizeof(gmacPartialAadCases) /
                    sizeof(gmacPartialAadCases[0]); i++) {
        uint8_t tag[16] = {0};

        WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                             gmacKey, 32,
                                             gmacIv, sizeof(gmacIv),
                                             gmacPartialAad,
                                             gmacPartialAadCases[i].aadSz,
                                             tag, sizeof(tag)),
                       WHAL_SUCCESS);

        WHAL_ASSERT_MEM_EQ(tag, gmacPartialAadCases[i].tag, sizeof(tag));
    }
}

static void Test_AesGmac_EmptyAad(void)
{
    uint8_t tag[16] = {0};

    WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                         gmacKey, 32,
                                         gmacIv, sizeof(gmacIv),
                                         NULL, 0,
                                         tag, sizeof(tag)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(tag, gmacTagAad0, sizeof(gmacTagAad0));
}

static void Test_AesGmac_BadIvSize(void)
{
    static const size_t badSz[] = { 0, 8, 13, 16 };
    const uint8_t iv[16] = {0};
    const uint8_t zero[16] = {0};
    uint8_t tag[16] = {0};
    size_t i;

    for (i = 0; i < sizeof(badSz) / sizeof(badSz[0]); i++) {
        WHAL_ASSERT_EQ(whal_AesGmac_Oneshot(BOARD_AES_GMAC_DEV,
                                             key, 32, iv, badSz[i],
                                             aad, sizeof(aad),
                                             tag, sizeof(tag)),
                       WHAL_ENOTSUP);
    }

    WHAL_ASSERT_MEM_EQ(tag, zero, sizeof(tag));
}

void whal_Test_AesGmac(void)
{
    WHAL_TEST_SUITE_START("aes_gmac");
    WHAL_TEST(Test_AesGmac_Basic);
    WHAL_TEST(Test_AesGmac_KnownAnswer);
    WHAL_TEST(Test_AesGmac_KnownAnswer128);
    WHAL_TEST(Test_AesGmac_PartialAad);
    WHAL_TEST(Test_AesGmac_EmptyAad);
    WHAL_TEST(Test_AesGmac_BadIvSize);
    WHAL_TEST_SUITE_END();
}
