static const struct {
    size_t msgSz;
    size_t chunkCnt;
    size_t chunks[5];
    const uint8_t *digest;
} hmacSha256ResidueCases[] = {
    { 0, 0, { 0 }, hmacSha256Residue0 },
    { 0, 1, { 0 }, hmacSha256Residue0 },
    { 1, 1, { 1 }, hmacSha256Residue1 },
    { 3, 1, { 3 }, hmacSha256Residue3 },
    { 7, 5, { 1, 1, 1, 1, 3 }, hmacSha256Residue7 },
    { 101, 2, { 50, 51 }, hmacSha256Residue101 },
    { 101, 3, { 50, 0, 51 }, hmacSha256Residue101 },
};

static void ResidueMsg(uint8_t *msg, size_t sz)
{
    size_t i;

    for (i = 0; i < sz; i++)
        msg[i] = (uint8_t)(i * 7 + 3);
}

static void Test_HmacSha256_StreamingResidue(void)
{
    uint8_t msg[101];
    size_t i;
    size_t j;

    ResidueMsg(msg, sizeof(msg));

    for (i = 0; i < sizeof(hmacSha256ResidueCases) /
                    sizeof(hmacSha256ResidueCases[0]); i++) {
        uint8_t digest[32] = {0};
        uint8_t oneshot[32] = {0};
        size_t off = 0;

        WHAL_ASSERT_EQ(whal_HmacSha256_Start(BOARD_HMAC_SHA256_DEV, hmacKey,
                                             sizeof(hmacKey)),
                       WHAL_SUCCESS);
        for (j = 0; j < hmacSha256ResidueCases[i].chunkCnt; j++) {
            size_t chunk = hmacSha256ResidueCases[i].chunks[j];

            WHAL_ASSERT_EQ(whal_HmacSha256_Process(BOARD_HMAC_SHA256_DEV,
                                                   msg + off, chunk),
                           WHAL_SUCCESS);
            off += chunk;
        }
        WHAL_ASSERT_EQ(whal_HmacSha256_Finalize(BOARD_HMAC_SHA256_DEV, digest,
                                                sizeof(digest)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(digest, hmacSha256ResidueCases[i].digest,
                           sizeof(digest));

        WHAL_ASSERT_EQ(whal_HmacSha256_Oneshot(BOARD_HMAC_SHA256_DEV, hmacKey,
                                               sizeof(hmacKey), msg,
                                               hmacSha256ResidueCases[i].msgSz,
                                               oneshot, sizeof(oneshot)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(oneshot, digest, sizeof(digest));
    }
}

