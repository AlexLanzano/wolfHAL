static void Test_HmacSha256_LongKey(void)
{
    static const struct {
        size_t keySz;
        const uint8_t *mac;
    } cases[] = {
        { 64, hmacSha256Key64Mac },
        { 131, hmacSha256Key131Mac },
    };
    uint8_t key[131];
    size_t i;

    for (i = 0; i < sizeof(key); i++)
        key[i] = 0xAA;

    for (i = 0; i < sizeof(cases) / sizeof(cases[0]); i++) {
        uint8_t digest[32] = {0};

        WHAL_ASSERT_EQ(whal_HmacSha256_Oneshot(BOARD_HMAC_SHA256_DEV, key,
                                               cases[i].keySz, hmacLongMsg,
                                               sizeof(hmacLongMsg), digest,
                                               sizeof(digest)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(digest, cases[i].mac, sizeof(digest));

        WHAL_ASSERT_EQ(whal_HmacSha256_Start(BOARD_HMAC_SHA256_DEV, key,
                                             cases[i].keySz),
                       WHAL_SUCCESS);
        WHAL_ASSERT_EQ(whal_HmacSha256_Process(BOARD_HMAC_SHA256_DEV,
                                               hmacLongMsg,
                                               sizeof(hmacLongMsg)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_EQ(whal_HmacSha256_Finalize(BOARD_HMAC_SHA256_DEV, digest,
                                                sizeof(digest)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(digest, cases[i].mac, sizeof(digest));
    }
}

