#include <stdint.h>
#include <wolfHAL/wolfHAL.h>
#include "wolfHAL_board.h"
#include "test.h"

/* NIST SP 800-38A F.1.3 AES-192-ECB, generated by
 * tests/crypto/gen_test_vectors.py */
static const uint8_t nistKey192[24] = {
    0x8E, 0x73, 0xB0, 0xF7, 0xDA, 0x0E, 0x64, 0x52,
    0xC8, 0x10, 0xF3, 0x2B, 0x80, 0x90, 0x79, 0xE5,
    0x62, 0xF8, 0xEA, 0xD2, 0x52, 0x2C, 0x6B, 0x7B,
};

static const uint8_t nistPt[16] = {
    0x6B, 0xC1, 0xBE, 0xE2, 0x2E, 0x40, 0x9F, 0x96,
    0xE9, 0x3D, 0x7E, 0x11, 0x73, 0x93, 0x17, 0x2A,
};

static const uint8_t nistEcbCt192[16] = {
    0xBD, 0x33, 0x4F, 0x1D, 0x6E, 0x45, 0xF2, 0x5F,
    0xF7, 0x12, 0xA2, 0x14, 0x57, 0x1F, 0xA5, 0xCC,
};

static void Test_AesEcb_KnownAnswer192(void)
{
    uint8_t ct[16] = {0};
    uint8_t pt[16] = {0};

    WHAL_ASSERT_EQ(whal_AesEcb_Oneshot(BOARD_AES_ECB_DEV, WHAL_CRYPTO_ENCRYPT,
                                        nistKey192, 24, nistPt, ct,
                                        sizeof(nistPt)),
                   WHAL_SUCCESS);
    WHAL_ASSERT_MEM_EQ(ct, nistEcbCt192, sizeof(nistEcbCt192));

    WHAL_ASSERT_EQ(whal_AesEcb_Oneshot(BOARD_AES_ECB_DEV, WHAL_CRYPTO_DECRYPT,
                                        nistKey192, 24, nistEcbCt192, pt,
                                        sizeof(nistEcbCt192)),
                   WHAL_SUCCESS);
    WHAL_ASSERT_MEM_EQ(pt, nistPt, sizeof(nistPt));
}

void whal_Test_AesEcb_Platform(void)
{
    WHAL_TEST_SUITE_START("aes_ecb_platform");
    WHAL_TEST(Test_AesEcb_KnownAnswer192);
    WHAL_TEST_SUITE_END();
}
