static const struct {
    size_t msgSz;
    size_t chunkCnt;
    size_t chunks[5];
    const uint8_t *digest;
} hmacSha224ResidueCases[] = {
    { 0, 0, { 0 }, hmacSha224Residue0 },
    { 0, 1, { 0 }, hmacSha224Residue0 },
    { 1, 1, { 1 }, hmacSha224Residue1 },
    { 3, 1, { 3 }, hmacSha224Residue3 },
    { 7, 5, { 1, 1, 1, 1, 3 }, hmacSha224Residue7 },
    { 101, 2, { 50, 51 }, hmacSha224Residue101 },
    { 101, 3, { 50, 0, 51 }, hmacSha224Residue101 },
};

static void ResidueMsg(uint8_t *msg, size_t sz)
{
    size_t i;

    for (i = 0; i < sz; i++)
        msg[i] = (uint8_t)(i * 7 + 3);
}

static void Test_HmacSha224_StreamingResidue(void)
{
    uint8_t msg[101];
    size_t i;
    size_t j;
    whal_Error err;

    ResidueMsg(msg, sizeof(msg));

    for (i = 0; i < sizeof(hmacSha224ResidueCases) /
                    sizeof(hmacSha224ResidueCases[0]); i++) {
        uint8_t digest[28] = {0};
        uint8_t oneshot[28] = {0};
        size_t off = 0;

        WHAL_ASSERT_EQ(whal_HmacSha224_Start(BOARD_HMAC_SHA224_DEV, hmacKey,
                                             sizeof(hmacKey)),
                       WHAL_SUCCESS);
        for (j = 0; j < hmacSha224ResidueCases[i].chunkCnt; j++) {
            size_t chunk = hmacSha224ResidueCases[i].chunks[j];

            WHAL_ASSERT_EQ(whal_HmacSha224_Process(BOARD_HMAC_SHA224_DEV,
                                                   msg + off, chunk),
                           WHAL_SUCCESS);
            off += chunk;
        }
        err = whal_HmacSha224_Finalize(BOARD_HMAC_SHA224_DEV, digest,
                                       sizeof(digest));
        if (err == WHAL_ENOTSUP && hmacSha224ResidueCases[i].msgSz == 0) {
            WHAL_ASSERT_EQ(whal_HmacSha224_Oneshot(BOARD_HMAC_SHA224_DEV,
                                                   hmacKey, sizeof(hmacKey),
                                                   msg, 0, oneshot,
                                                   sizeof(oneshot)),
                           WHAL_ENOTSUP);
            continue;
        }
        WHAL_ASSERT_EQ(err, WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(digest, hmacSha224ResidueCases[i].digest,
                           sizeof(digest));

        WHAL_ASSERT_EQ(whal_HmacSha224_Oneshot(BOARD_HMAC_SHA224_DEV, hmacKey,
                                               sizeof(hmacKey), msg,
                                               hmacSha224ResidueCases[i].msgSz,
                                               oneshot, sizeof(oneshot)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(oneshot, digest, sizeof(digest));
    }
}

