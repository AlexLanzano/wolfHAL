static const uint8_t hmacSha1Residue101[20] = {
    0x38, 0xCB, 0xE9, 0x67, 0x23, 0x17, 0xAD, 0x7F,
    0x7F, 0xE0, 0x85, 0x1C, 0x3D, 0x34, 0x0F, 0x61,
    0x34, 0x3A, 0xF9, 0x81,
};

static const struct {
    size_t msgSz;
    size_t chunkCnt;
    size_t chunks[5];
    const uint8_t *digest;
} hmacSha1ResidueCases[] = {
    { 0, 0, { 0 }, hmacSha1Residue0 },
    { 0, 1, { 0 }, hmacSha1Residue0 },
    { 1, 1, { 1 }, hmacSha1Residue1 },
    { 3, 1, { 3 }, hmacSha1Residue3 },
    { 7, 5, { 1, 1, 1, 1, 3 }, hmacSha1Residue7 },
    { 101, 2, { 50, 51 }, hmacSha1Residue101 },
    { 101, 3, { 50, 0, 51 }, hmacSha1Residue101 },
};

static void ResidueMsg(uint8_t *msg, size_t sz)
{
    size_t i;

    for (i = 0; i < sz; i++)
        msg[i] = (uint8_t)(i * 7 + 3);
}

static void Test_HmacSha1_StreamingResidue(void)
{
    uint8_t msg[101];
    size_t i;
    size_t j;
    whal_Error err;

    ResidueMsg(msg, sizeof(msg));

    for (i = 0; i < sizeof(hmacSha1ResidueCases) /
                    sizeof(hmacSha1ResidueCases[0]); i++) {
        uint8_t digest[20] = {0};
        uint8_t oneshot[20] = {0};
        size_t off = 0;

        WHAL_ASSERT_EQ(whal_HmacSha1_Start(BOARD_HMAC_SHA1_DEV, hmacKey,
                                           sizeof(hmacKey)),
                       WHAL_SUCCESS);
        for (j = 0; j < hmacSha1ResidueCases[i].chunkCnt; j++) {
            size_t chunk = hmacSha1ResidueCases[i].chunks[j];

            WHAL_ASSERT_EQ(whal_HmacSha1_Process(BOARD_HMAC_SHA1_DEV,
                                                 msg + off, chunk),
                           WHAL_SUCCESS);
            off += chunk;
        }
        err = whal_HmacSha1_Finalize(BOARD_HMAC_SHA1_DEV, digest,
                                     sizeof(digest));
        if (err == WHAL_ENOTSUP && hmacSha1ResidueCases[i].msgSz == 0) {
            WHAL_ASSERT_EQ(whal_HmacSha1_Oneshot(BOARD_HMAC_SHA1_DEV,
                                                 hmacKey, sizeof(hmacKey),
                                                 msg, 0, oneshot,
                                                 sizeof(oneshot)),
                           WHAL_ENOTSUP);
            continue;
        }
        WHAL_ASSERT_EQ(err, WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(digest, hmacSha1ResidueCases[i].digest,
                           sizeof(digest));

        WHAL_ASSERT_EQ(whal_HmacSha1_Oneshot(BOARD_HMAC_SHA1_DEV, hmacKey,
                                             sizeof(hmacKey), msg,
                                             hmacSha1ResidueCases[i].msgSz,
                                             oneshot, sizeof(oneshot)),
                       WHAL_SUCCESS);
        WHAL_ASSERT_MEM_EQ(oneshot, digest, sizeof(digest));
    }
}

void whal_Test_HmacSha1(void)
{
    WHAL_TEST_SUITE_START("hmac_sha1");
    WHAL_TEST(Test_HmacSha1_KnownAnswer);
    WHAL_TEST(Test_HmacSha1_Streaming);
    WHAL_TEST(Test_HmacSha1_UnalignedKey);
    WHAL_TEST(Test_HmacSha1_LongKey);
    WHAL_TEST(Test_HmacSha1_StreamingResidue);
    WHAL_TEST_SUITE_END();
}
